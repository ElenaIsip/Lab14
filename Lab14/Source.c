#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <math.h>
#include <locale.h>


#define N 10

int main(void) {
    setlocale(LC_ALL, "Russian");

    // 1. Объявление массива
    float A[N];
    float temp;

    // Массивы для хранения исходных и новых значений (для вывода в таблицу)
    float original[N];
    float rounded[N];

    printf("Заполнение массива:\n");

    // 2. Заполнение массива с консоли
    for (int i = 0; i < N; i++) {
        printf("a[%d] = ", i + 1);
        if (scanf("%f", &temp) != 1) {
            printf("Ошибка ввода!\n");
            return 1;
        }
        A[i] = temp;
        original[i] = temp; // Сохраняем исходное значение
    }

    // 3. Преобразование: округление в большую сторону
    float sum = 0.0; // Переменная для суммы элементов
    for (int i = 0; i < N; i++) {
        rounded[i] = ceil(A[i]); // Округляем
        sum += rounded[i];       // Сразу считаем сумму новых элементов
    }

    // 6. Вычисление среднего арифметического
    float average = sum / N;

    // 4. Вывод результатов в виде таблицы
    printf("\n------------------------------------------------------\n");
    printf("| %-7s | %-17s | %-15s |\n", "Индекс", "Исходное значение", "Новое значение");
    printf("------------------------------------------------------\n");

    for (int i = 0; i < N; i++) {
        // Выводим индекс (от 1 до 10), исходное число (с 2 знаками после запятой) 
        // и новое (как целое, так как после ceil дробной части нет)
        printf("| %-7d | %-17.2f | %-15.0f |\n", i + 1, original[i], rounded[i]);
    }
    printf("------------------------------------------------------\n");

    // Вывод среднего арифметического
    printf("\nСреднее арифметическое преобразованных элементов: %.2f\n", average);

    return 0;
}